def build_tilesets():
    out = {}
    meta = {}
    for name, cfg in BIOMES.items():
        rng = random.Random(f"tiles-{name}")
        sheet = blank(T * 8, T * 4)
        for i in range(8):
            paste(sheet, _floor_tile(cfg["floor"], rng, i), i * T, 0)
        for i, rows in enumerate(DECALS[cfg["decals"]]):
            paste(sheet, grid(rows), i * T, T)
        for i in range(8):
            paste(sheet, _face_tile(cfg["face"], rng, i), i * T, 2 * T)
        for i in range(4):
            paste(sheet, _top_tile(cfg["top"], rng, i), i * T, 3 * T)
        out[f"tiles_{name}"] = sheet
        meta[name] = {
            "rim": "#%02x%02x%02x" % PAL[cfg["face"]["top"]][:3],
            "edge": "#%02x%02x%02x" % PAL[cfg["face"]["light"]][:3],
        }
    return out, meta


