def build_props():
    sheets = []
    images = {}
    for biome in ("sewer", "crypt", "foundry", "plaza"):
        cfg = BIOMES[biome]
        images[f"pillar_{biome}"] = _pillar(cfg)
    for kind in ("sewer", "crypt", "foundry"):
        sb = SheetBuilder(f"pot_{kind}", 16, 16, origin=(8, 13))
        whole = _pot(kind)
        broken = blank(16, 16)
        paste(broken, whole.crop((0, 9, 16, 16)), 0, 9)
        sb.add("idle", [whole])
        sb.add("broken", [broken], fps=1, loop=False)
        sheets.append(sb)
    # brazier
    sb = SheetBuilder("brazier", 16, 20, origin=(8, 16))
    base = grid(BRAZIER_BASE)
    unlit = base.copy()
    paste(unlit, grid(["...0021232120...", "....00000000...."]), 0, 6)
    sb.add("unlit", [unlit], fps=1)
    lit = []
    for f in FLAMES:
        img = base.copy()
        paste(img, grid(f), 0, 1)
        lit.append(img)
    sb.add("lit", lit, fps=10)
    sheets.append(sb)
    return sheets, images
