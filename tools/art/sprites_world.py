def _pillar(cfg):
    """16x24 block: cap (8px) + face (16px)."""
    face = cfg["face"]
    img = blank(16, 24)
    px = img.load()
    for y in range(24):
        for x in range(1, 15):
            if y < 7:
                c = face["top"] if y in (1,) else (face["light"] if y < 3 else face["base"])
                if y == 0:
                    c = "0"
            else:
                ly = (y - 7) % 4
                lx = (x + (2 if ((y - 7) // 4) % 2 else 0)) % 6
                c = face["base"]
                if ly == 0 or lx == 0:
                    c = face["mortar"]
                elif ly == 1:
                    c = face["light"]
                elif ly == 3:
                    c = face["dark"]
            if x in (1, 14):
                c = "0"
            if y == 23:
                c = "0"
            if y == 6:
                c = face["mortar"]
            px[x, y] = PAL[c]
    # side shading
    for y in range(7, 23):
        px[2, y] = PAL[face["light"]]
        px[13, y] = PAL[face["dark"]]
    return img


