def _set(px, x, y, ch):
    if 0 <= x < T and 0 <= y < T:
        px[x, y] = PAL[ch]


def _floor_tile(cfg, rng, variant):
    img = blank(T, T)
    px = img.load()
    style = cfg["style"]
    # base fill with soft noise
    for y in range(T):
        for x in range(T):
            px[x, y] = PAL[cfg["base"]]
    if style == "slabs":
        # 8x8 slabs with mortar on x=0 / y=0 lines
        for y in range(T):
            for x in range(T):
                lx, ly = x % 8, y % 8
                if lx == 0 or ly == 0:
                    _set(px, x, y, cfg["mortar"])
                elif lx == 1 or ly == 1:
                    _set(px, x, y, cfg["light"] if rng.random() < 0.7 else cfg["base"])
                elif lx == 7 or ly == 7:
                    _set(px, x, y, cfg["dark"])
        # some slabs slightly darker
        for sx in (0, 8):
            for sy in (0, 8):
                if rng.random() < 0.3:
                    for y in range(sy + 2, sy + 7):
                        for x in range(sx + 2, sx + 7):
                            if dither_pick(x, y, 0.5):
                                _set(px, x, y, cfg["dark"])
    elif style == "bricks":
        # 8x4 running bond
        for y in range(T):
            row = y // 4
            off = 4 if row % 2 else 0
            for x in range(T):
                lx = (x + off) % 8
                ly = y % 4
                if ly == 0 or lx == 0:
                    _set(px, x, y, cfg["mortar"])
                elif ly == 1 and lx < 7:
                    _set(px, x, y, cfg["light"])
                elif ly == 3 or lx == 7:
                    _set(px, x, y, cfg["dark"])
    elif style == "plates":
        for y in range(T):
            for x in range(T):
                if x == 0 or y == 0:
                    _set(px, x, y, cfg["mortar"])
                elif x == 1 or y == 1:
                    _set(px, x, y, cfg["light"])
                elif x == 15 or y == 15:
                    _set(px, x, y, cfg["dark"])
        for (rx, ry) in ((3, 3), (12, 3), (3, 12), (12, 12)):
            _set(px, rx, ry, cfg["light"])
            _set(px, rx + 1, ry + 1, cfg["dark"])
        if variant % 3 == 1:
            for x in range(4, 12):
                _set(px, x, 8, cfg["dark"])
                _set(px, x, 9, cfg["light"])
    elif style == "cobble":
        # irregular cobbles via jittered grid cells (5x5 / 6x6)
        cells = [(0, 0, 6, 5), (6, 0, 5, 5), (11, 0, 5, 5), (0, 5, 4, 6), (4, 5, 7, 6), (11, 5, 5, 6), (0, 11, 7, 5), (7, 11, 5, 5), (12, 11, 4, 5)]
        for (cx, cy, cw, ch) in cells:
            shade = rng.choice([cfg["base"], cfg["base"], cfg["light"], cfg["dark"]])
            for y in range(cy, cy + ch):
                for x in range(cx, cx + cw):
                    edge_l = x == cx
                    edge_t = y == cy
                    if edge_l or edge_t:
                        _set(px, x, y, cfg["mortar"])
                    elif y == cy + 1 or x == cx + 1:
                        _set(px, x, y, cfg["light"] if shade != cfg["dark"] else cfg["base"])
                    elif y == cy + ch - 1 or x == cx + cw - 1:
                        _set(px, x, y, cfg["dark"])
                    else:
                        _set(px, x, y, shade)
    # specks
    n_specks = rng.randint(2, 6)
    for _ in range(n_specks):
        x, y = rng.randrange(2, 15), rng.randrange(2, 15)
        if px[x, y] != PAL[cfg["mortar"]]:
            _set(px, x, y, rng.choice(cfg["speck"]))
    # crack on some variants
    if variant in (5, 7):
        x, y = rng.randrange(3, 12), rng.randrange(3, 12)
        for _ in range(rng.randint(5, 9)):
            _set(px, x, y, cfg["mortar"])
            x += rng.choice((-1, 0, 1, 1))
            y += rng.choice((0, 1, 1))
    return img


def _face_tile(cfg, rng, variant):
    img = blank(T, T)
    px = img.load()
    style = cfg["style"]
    for y in range(T):
        for x in range(T):
            px[x, y] = PAL[cfg["base"]]
    if style == "bricks":
        for y in range(T):
            row = (y - 1) // 4
            off = 4 if row % 2 else 0
            for x in range(T):
                lx = (x + off) % 8
                ly = (y - 1) % 4
                if ly == 0 or lx == 0:
                    _set(px, x, y, cfg["mortar"])
                elif ly == 1:
                    _set(px, x, y, cfg["light"])
                elif ly == 3:
                    _set(px, x, y, cfg["dark"])
    elif style == "blocks":
        for y in range(T):
            for x in range(T):
                lx = x % 8 if y < 8 else (x + 4) % 8
                ly = (y - 1) % 7
                if ly == 0 or lx == 0:
                    _set(px, x, y, cfg["mortar"])
                elif ly == 1 or lx == 1:
                    _set(px, x, y, cfg["light"])
                elif ly == 6 or lx == 7:
                    _set(px, x, y, cfg["dark"])
    elif style == "plates":
        for y in range(T):
            for x in range(T):
                if x in (0, 8) or y in (1,):
                    _set(px, x, y, cfg["mortar"])
                elif x in (1, 9):
                    _set(px, x, y, cfg["light"])
                elif x in (7, 15):
                    _set(px, x, y, cfg["dark"])
        for ry in (4, 11):
            for rx in (3, 12):
                _set(px, rx, ry, cfg["light"])
                _set(px, rx, ry + 1, cfg["mortar"])
    # top lip highlight and bottom shadow (wall meets floor)
    for x in range(T):
        _set(px, x, 0, cfg["top"])
        _set(px, x, T - 1, "1")
        if dither_pick(x, T - 2, 0.5):
            _set(px, x, T - 2, cfg["dark"])
    acc = cfg["accent"]
    if variant in (1, 4):
        # moss / drip streaks from the top
        for _ in range(rng.randint(2, 4)):
            x = rng.randrange(1, 15)
            for y in range(1, rng.randint(4, 10)):
                _set(px, x, y, acc[0] if y > 2 else acc[1])
    if variant == 6:
        # special A: a grate / niche / vent
        for y in range(4, 13):
            for x in range(4, 12):
                _set(px, x, y, "1")
        for x in range(4, 12):
            _set(px, x, 4, cfg["light"])
        for x in (5, 7, 9, 11):
            for y in range(5, 13):
                _set(px, x, y, cfg["dark"])
        _set(px, 6, 12, acc[0])
    if variant == 7:
        # special B: pipe / candle niche
        for y in range(3, 14):
            for x in range(6, 10):
                _set(px, x, y, cfg["mortar"])
        for y in range(4, 13):
            _set(px, 7, y, cfg["light"])
            _set(px, 8, y, cfg["base"])
        for x in range(5, 11):
            _set(px, x, 3, cfg["dark"])
            _set(px, x, 13, cfg["dark"])
    return img


def _top_tile(cfg, rng, variant):
    img = blank(T, T)
    px = img.load()
    for y in range(T):
        for x in range(T):
            px[x, y] = PAL[cfg["fill"]]
    for _ in range(4 + variant * 2):
        x, y = rng.randrange(1, 15), rng.randrange(1, 15)
        _set(px, x, y, cfg["pattern"])
    return img


