def build_relic_icons():
    sheet = blank(8 * 16, 6 * 16)
    for idx, rows in ICONS.items():
        img = blank(16, 16)
        paste(img, grid(rows), 1, 1)
        img = outline(img, PAL["0"])
        sheet.alpha_composite(img, ((idx % 8) * 16, (idx // 8) * 16))
    return {"relic_icons": sheet}
