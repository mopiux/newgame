def main():
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    out = os.path.join(root, "i18n", "strings.csv")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    bad = []
    for k, (es, en) in S.items():
        if re.findall(r"%[sd]", es) != re.findall(r"%[sd]", en):
            bad.append(k)
    if bad:
        print("placeholder mismatch:", bad)
        sys.exit(1)
    with open(out, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["keys", "es", "en"])
        for k in S:
            w.writerow([k, S[k][0], S[k][1]])
    print(f"wrote {len(S)} strings to {out}")


if __name__ == "__main__":
    main()
